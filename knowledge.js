  function tokenize(s) {
    var t = String(s || '').toLowerCase();
    // ASCII 词
    var ascii = t.split(/[^a-z0-9]+/).filter(Boolean);
    // 中文连续段 → 整词 + 二元组（bigram）
    var cjk = (t.match(/[\u4e00-\u9fa5]+/g) || []);
    var out = [];
    ascii.forEach(function (a) { out.push(a); });
    cjk.forEach(function (c) {
      out.push(c);
      for (var i = 0; i < c.length - 1; i++) out.push(c.slice(i, i + 2));
    });
    return out;
  }

  function inText(text, words) {
    var t = String(text || '').toLowerCase();
    var hit = 0;
    for (var i = 0; i < words.length; i++) {
      var w = words[i];
      if (!w) continue;
      // 单字符只匹配 ASCII 字母数字（如 P、t、F、χ），避免单字中文噪音
      if (w.length === 1 && /[a-z0-9]/.test(w)) {
        if (t.indexOf(w) >= 0) hit++;
      } else if (w.length >= 2 && t.indexOf(w) >= 0) {
        hit++;
      }
    }
    return hit;
  }

  /**
   * 检索知识库：返回按相关度排序的条目
   * @param {string} query 用户问题
   * @param {number} topN 返回条数
   * @returns {Array<{type,title,content,source,score}>}
   */
  function search(query, topN) {
    topN = topN || 4;
    var words = tokenize(query);
    if (!words.length) return [];
    var scored = [];

    ENTRIES.forEach(function (e) {
      var score = 0;
      score += inText(e.keywords.join(' '), words) * 3;
      score += inText(e.title, words) * 2;
      score += inText(e.content, words);
      if (score > 0) scored.push({ type: 'entry', title: e.title, content: e.content, source: e.source, course: e.course, tags: e.tags, score: score });
    });

    CONFUSIONS.forEach(function (c) {
      var score = 0;
      score += inText(c.pair + ' ' + c.a + ' ' + c.b, words) * 4;
      score += inText(c.diff, words);
      if (score > 0) scored.push({ type: 'confusion', title: c.pair, content: c.diff, source: c.source, score: score });
    });

    QA.forEach(function (q) {
      var score = 0;
      score += inText(q.q, words) * 4;
      score += inText(q.a, words);
      if (score > 0) scored.push({ type: 'qa', title: q.q, content: q.a, source: q.source, score: score });
    });

    FRONTIER.forEach(function (f) {
      var score = 0;
      score += inText(f.title, words) * 2;
      score += inText(f.content, words);
      if (score > 0) scored.push({ type: 'frontier', title: f.title, content: f.content, source: f.source, score: score });
    });

    scored.sort(function (a, b) { return b.score - a.score; });
    return scored.slice(0, topN);
  }

